import { hotspotAngles, GALLERY, HERO, PANORAMAS } from "./scenes/index";
import { TILE_SIZE, cubeLevels } from "@synapse/cubemap";
import type { MasterplanModel } from "./glb";

export const GENERATOR_VERSION = "1.0.0";
export const PANO_WIDTH = 4096;
export const PANO_HEIGHT = 2048;

const r4 = (v: number): number => Math.round(v * 10000) / 10000;
const r2 = (v: number): number => Math.round(v * 100) / 100;

export interface ManifestHotspot {
  label: string;
  yaw: number;
  pitch: number;
  targetSlug: string | null;
  type: "NAVIGATION" | "INFO";
  description?: string;
}

export interface ManifestPanorama {
  slug: string;
  name: string;
  file: string;
  preview: string;
  thumb: string;
  /** Marzipano cube tiles generated from the same panorama. */
  tiles: { path: string; tileSize: number; faceSizes: number[] };
  width: number;
  height: number;
  initialView: { yaw: number; pitch: number; fov: number };
  floorPlanPoint: { x: number; y: number };
  hotspots: ManifestHotspot[];
}

export interface Manifest {
  generatedAt: string;
  generatorVersion: string;
  license: string;
  /** yaw 0 = looking toward the image center, positive yaw turns right, positive pitch looks UP. */
  convention: "marzipano";
  panoramas: ManifestPanorama[];
  model: { file: string; nodes: string[]; units: Array<{ code: string; node: string; labelPosition: [number, number, number] }> };
  floorplan: { file: string; width: number; height: number };
  gallery: Array<{ file: string; title: string }>;
  hero: string;
}

/** Pure: builds the manifest from the scene definitions and the generated model. Paths are relative to storage/demo. */
export function buildManifest(model: Pick<MasterplanModel, "nodes" | "units">, generatedAt: string): Manifest {
  return {
    generatedAt,
    generatorVersion: GENERATOR_VERSION,
    license: "Generated by Synapse demo generator, CC0 / project-owned",
    convention: "marzipano",
    panoramas: PANORAMAS.map((p) => ({
      slug: p.slug,
      name: p.name,
      file: `panoramas/${p.slug}.jpg`,
      preview: `panoramas/${p.slug}-preview.jpg`,
      thumb: `thumbs/${p.slug}.jpg`,
      tiles: { path: `panoramas/${p.slug}-tiles`, tileSize: TILE_SIZE, faceSizes: cubeLevels(PANO_WIDTH) },
      width: PANO_WIDTH,
      height: PANO_HEIGHT,
      initialView: { yaw: r4(p.initialView.yaw), pitch: r4(p.initialView.pitch), fov: r4(p.initialView.fov) },
      floorPlanPoint: { x: r2(p.floorPlanPoint.x), y: r2(p.floorPlanPoint.y) },
      hotspots: p.hotspots.map((h) => {
        const a = hotspotAngles(p, h);
        const out: ManifestHotspot = { label: h.label, yaw: r4(a.yaw), pitch: r4(a.pitch), targetSlug: h.targetSlug, type: h.type };
        if (h.description) out.description = h.description;
        return out;
      }),
    })),
    model: { file: "models/masterplan.glb", nodes: model.nodes, units: model.units },
    floorplan: { file: "floorplans/villa-6.svg", width: 1000, height: 700 },
    gallery: GALLERY.map((g) => ({ file: g.file, title: g.title })),
    hero: HERO.file,
  };
}
